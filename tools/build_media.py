"""Package the supplied one-track-per-BPM music library (source files are read-only).
Usage: python tools/build_media.py /path/to/new_BPM_folder
Karaoke is an owner-provided recording, not generated by this script.
"""
import hashlib
import json
from pathlib import Path
import sys
import zipfile

ROOT = Path(__file__).resolve().parents[1]
if len(sys.argv) > 1:
    source = Path(sys.argv[1]).resolve(strict=True)
    tracks = []
    for bpm in range(60, 151, 10):
        files = sorted(p for p in (source / str(bpm)).iterdir() if p.suffix.lower() in (".mp3", ".wav", ".m4a", ".ogg", ".flac"))
        if len(files) != 1:
            raise ValueError(f"{bpm}: expected exactly one audio file, found {len(files)}")
        tracks.append((bpm, files[0]))
    with zipfile.ZipFile(ROOT / "BPM_folder.zip", "w", zipfile.ZIP_STORED) as archive:
        for bpm, track in tracks:
            archive.write(track, f"BPM_folder/{bpm}/{track.name}")
    manifest = {"source": "User-supplied replacement music; owner confirms generated during active Suno Pro/Premier subscription", "tracks": [
        {"bpm": bpm, "file": f"{bpm}/{track.name}", "sha256": hashlib.sha256(track.read_bytes()).hexdigest()}
        for bpm, track in tracks]}
    (ROOT / "music_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
